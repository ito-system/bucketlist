export function LegalScreen({ type }: Props) {
  const navigation = useNavigation();
  const content =
    type === 'terms' ? TERMS_CONTENT :
    type === 'privacy' ? PRIVACY_CONTENT :
    TOKUSHOHO_CONTENT;

  return (
    <SafeAreaView className="flex-1 bg-amber-50">
      {/* ヘッダー */}
      <View className="flex-row items-center px-4 pt-2 pb-4">
        <TouchableOpacity
          className="w-9 h-9 items-center justify-center"
          onPress={() => navigation.goBack()}
        >
          <ArrowLeft size={22} color="#111827" />
        </TouchableOpacity>
        <Text className="flex-1 text-lg font-bold text-amber-900 text-center mr-9">
          {content.title}
        </Text>
      </View>

      {/* スクロール可能な本文枠 */}
      <View className="flex-1 mx-4 mb-6 bg-white rounded-2xl border border-amber-100 overflow-hidden">
        <ScrollView
          className="flex-1 px-5 pt-5"
          contentContainerStyle={{ paddingBottom: 24 }}
          showsVerticalScrollIndicator={true}
          indicatorStyle="black"
        >
          {content.sections.map((section) => (
            <View key={section.heading} className="mb-6">
              <Text className="text-sm font-bold text-amber-900 mb-2">
                {section.heading}
              </Text>
              <Text className="text-sm text-gray-600 leading-6">
                {section.body}
              </Text>
            </View>
          ))}
        </ScrollView>
      </View>
    </SafeAreaView>
  );
}
